"""Insights & recommended actions – dark summary card from the approved design."""
from __future__ import annotations

import design
import streamlit as st
from ui import ViewContext


def render(ctx: ViewContext) -> None:
    latest = ctx.repo.latest_insight(ctx.tax.industry)
    if not latest:
        st.markdown(design.dark_card("Auto summary", "No insights yet – they are generated by the daily run."),
                    unsafe_allow_html=True)
        return
    head = f"Auto summary · {latest[0].astimezone():%H:%M %d/%m}"
    st.markdown(design.dark_card(head, design.md_lite(latest[1])), unsafe_allow_html=True)
